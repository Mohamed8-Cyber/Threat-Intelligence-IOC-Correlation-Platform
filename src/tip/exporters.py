"""Exports: CSV, JSON, plain blocklists, STIX 2.1 indicator bundles and an Excel workbook.

STIX relationships are deliberately not exported in this release. A relationship type that a
real consumer rejects is worse than none. See docs/COUNCIL_DECISIONS.md.
"""

from __future__ import annotations

import csv
import io
import json
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from .models import IOCType, from_iso

STIX_NAMESPACE = uuid.UUID("6f1c2b8e-3d4a-4e5b-9a7c-1d2e3f4a5b6c")
CSV_FIELDS = ["type", "value", "score", "severity", "tags", "campaigns", "sources",
              "first_seen", "last_seen"]
BLOCKLIST_TYPES = (IOCType.IPV4, IOCType.IPV6, IOCType.DOMAIN, IOCType.URL)
TYPE_ORDER = [t.value for t in IOCType]

_STIX_PATHS = {
    IOCType.IPV4: "ipv4-addr:value",
    IOCType.IPV6: "ipv6-addr:value",
    IOCType.DOMAIN: "domain-name:value",
    IOCType.URL: "url:value",
    IOCType.EMAIL: "email-addr:value",
    IOCType.MD5: "file:hashes.'MD5'",
    IOCType.SHA1: "file:hashes.'SHA-1'",
    IOCType.SHA256: "file:hashes.'SHA-256'",
}


def stix_pattern(kind: IOCType, value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    if kind is IOCType.CIDR:
        path = "ipv6-addr:value" if ":" in value else "ipv4-addr:value"
        return f"[{path} ISSUBSET '{escaped}']"
    return f"[{_STIX_PATHS[kind]} = '{escaped}']"


def _stamp(iso_text: str) -> str:
    return from_iso(iso_text).astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def to_csv(rows: list[dict[str, Any]]) -> str:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=CSV_FIELDS, extrasaction="ignore")
    writer.writeheader()
    for row in rows:
        writer.writerow({**row, "tags": ";".join(row["tags"]),
                         "campaigns": ";".join(row["campaigns"])})
    return buffer.getvalue()


def to_json(rows: list[dict[str, Any]]) -> str:
    return json.dumps(rows, indent=2, ensure_ascii=False)


def to_blocklist(rows: list[dict[str, Any]]) -> str:
    lines = ["# Generated by tip-platform. One indicator per line."]
    lines += [row["value"] for row in rows if IOCType(row["type"]) in BLOCKLIST_TYPES]
    return "\n".join(lines) + "\n"


def to_stix(rows: list[dict[str, Any]], now: datetime | None = None) -> dict[str, Any]:
    """A STIX 2.1 bundle of indicators. IDs are deterministic, so re-exports are stable."""
    now = now or datetime.now(timezone.utc)
    objects: list[dict[str, Any]] = []
    for row in rows:
        kind = IOCType(row["type"])
        key = f"{kind.value}:{row['value']}"
        high = row["severity"] in ("high", "critical")
        objects.append({
            "type": "indicator",
            "spec_version": "2.1",
            "id": f"indicator--{uuid.uuid5(STIX_NAMESPACE, key)}",
            "created": _stamp(row["first_seen"]),
            "modified": _stamp(row["last_seen"]),
            "name": row["value"],
            "indicator_types": ["malicious-activity" if high else "anomalous-activity"],
            "pattern": stix_pattern(kind, row["value"]),
            "pattern_type": "stix",
            "valid_from": _stamp(row["first_seen"]),
            "confidence": round(row["score"] * 100),
            "x_tip_severity": row["severity"],
            "x_tip_tags": row["tags"],
            "x_tip_campaigns": row["campaigns"],
        })
    return {
        "type": "bundle",
        "id": f"bundle--{uuid.uuid4()}",
        "objects": objects,
    }


def to_xlsx(rows: list[dict[str, Any]], path: str | Path) -> Path:
    """Workbook with an IOCs sheet and a Summary sheet whose figures are live formulas."""
    workbook = Workbook()
    summary = workbook.active
    summary.title = "Summary"
    sheet = workbook.create_sheet("IOCs")

    headers = ["Type", "Value", "Triage score", "Severity", "Tags", "Campaigns",
               "Sources", "First seen", "Last seen"]
    sheet.append(headers)
    for row in rows:
        sheet.append([row["type"], row["value"], row["score"], row["severity"],
                      ";".join(row["tags"]), ";".join(row["campaigns"]), row["sources"],
                      row["first_seen"], row["last_seen"]])
    last = max(len(rows) + 1, 2)

    header_font = Font(name="Arial", bold=True, color="FFFFFF", size=10)
    header_fill = PatternFill("solid", fgColor="1F3A4D")
    body_font = Font(name="Arial", size=10)
    for cell in sheet[1]:
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(vertical="center")
    for row_cells in sheet.iter_rows(min_row=2, max_row=last):
        for cell in row_cells:
            cell.font = body_font
    for r in range(2, last + 1):
        sheet.cell(r, 3).number_format = "0.0%"
    for index, width in enumerate([10, 42, 13, 12, 28, 28, 10, 22, 22], start=1):
        sheet.column_dimensions[get_column_letter(index)].width = width
    sheet.freeze_panes = "A2"
    sheet.auto_filter.ref = f"A1:I{last}"

    summary["A1"] = "Threat intelligence export: summary"
    summary["A1"].font = Font(name="Arial", bold=True, size=14)
    summary["A2"] = ("Every figure below is a formula over the IOCs sheet. "
                     "Triage score is a decayed rank, not a probability.")
    summary["A2"].font = Font(name="Arial", italic=True, size=9, color="5B6B77")

    header_row = 4
    for col, title in enumerate(["Indicator type", "Count", "Share"], start=1):
        cell = summary.cell(header_row, col, title)
        cell.font = header_font
        cell.fill = header_fill

    first = header_row + 1
    total_row = first + len(TYPE_ORDER)
    for offset, kind in enumerate(TYPE_ORDER):
        r = first + offset
        summary.cell(r, 1, kind).font = body_font
        summary.cell(r, 2, f"=COUNTIF(IOCs!$A$2:$A${last},A{r})").font = body_font
        share = summary.cell(r, 3, f"=IF($B${total_row}=0,0,B{r}/$B${total_row})")
        share.number_format = "0.0%"
        share.font = body_font
    summary.cell(total_row, 1, "Total").font = Font(name="Arial", bold=True, size=10)
    summary.cell(total_row, 2, f"=SUM(B{first}:B{total_row - 1})").font = Font(
        name="Arial", bold=True, size=10)

    metrics_row = total_row + 2
    metrics = [
        ("High or critical severity",
         f'=COUNTIF(IOCs!$D$2:$D${last},"high")+COUNTIF(IOCs!$D$2:$D${last},"critical")', "0"),
        ("Average triage score", f"=IFERROR(AVERAGE(IOCs!$C$2:$C${last}),0)", "0.0%"),
    ]
    for offset, (label, formula, number_format) in enumerate(metrics):
        r = metrics_row + offset
        summary.cell(r, 1, label).font = body_font
        value = summary.cell(r, 2, formula)
        value.number_format = number_format
        value.font = body_font

    summary.column_dimensions["A"].width = 30
    summary.column_dimensions["B"].width = 14
    summary.column_dimensions["C"].width = 12
    workbook.calculation.fullCalcOnLoad = True
    workbook.save(path)
    return Path(path)
